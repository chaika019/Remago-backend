package com.adrotation.crm.schedule.dto;

import com.adrotation.crm.schedule.enums.ShiftStatus;
import jakarta.validation.constraints.NotNull;

public final class ShiftDtos {
    private ShiftDtos() {}

    public record CreateShiftRequest(
            @NotNull Long cityId,
            @NotNull Long weekId,
            ShiftStatus status,
            Long companyId,
            Long responsiblePersonId,
            boolean a4Sold,
            String failureReason
    ) {}

    public record UpdateShiftRequest(
            ShiftStatus status,
            Long companyId,
            Long responsiblePersonId,
            Boolean a4Sold,
            String failureReason,
            Boolean clearCompany,
            Boolean clearResponsiblePerson
    ) {}

    public record ShiftResponse(
            Long id,
            Long cityId,
            String cityName,
            Long weekId,
            int isoWeekNumber,
            ShiftStatus status,
            String statusLabel,
            String colorHex,
            Long companyId,
            String companyName,
            Long responsiblePersonId,
            String responsiblePersonName,
            Long autoGeneratedFromShiftId,
            boolean a4Sold,
            String failureReason,
            String weekDriveFolderUrl
    ) {}

    public record ShiftProposalRequest(
            @NotNull ShiftStatus desiredStatus,
            String comment
    ) {}

    public record ShiftStatusMeta(
            ShiftStatus code,
            int legendNumber,
            String label,
            String colorHex
    ) {}
}
