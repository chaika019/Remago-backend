package com.adrotation.crm.schedule.entity;

import com.adrotation.crm.city.entity.City;
import com.adrotation.crm.company.entity.Company;
import com.adrotation.crm.user.entity.AppUser;
import com.adrotation.crm.shared.entity.BaseEntity;
import com.adrotation.crm.schedule.enums.ShiftStatus;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
@Entity
@Table(name = "shifts")
public class Shift extends BaseEntity {
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "city_id", nullable = false)
    private City city;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "week_id", nullable = false)
    private WeekPeriod week;

    @Enumerated(EnumType.STRING)
    private ShiftStatus status = ShiftStatus.PLANNED;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "company_id")
    private Company company;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "responsible_person_id")
    private AppUser responsiblePerson;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "auto_generated_from_shift_id")
    private Shift autoGeneratedFromShift;

    private boolean a4Sold;

    @jakarta.persistence.Column(columnDefinition = "text")
    private String failureReason;
}
