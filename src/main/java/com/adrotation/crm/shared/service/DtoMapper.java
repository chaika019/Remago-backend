package com.adrotation.crm.shared.service;

import com.adrotation.crm.audit.dto.AuditLogDto;
import com.adrotation.crm.audit.entity.AuditLog;
import com.adrotation.crm.city.dto.CityDtos;
import com.adrotation.crm.city.entity.City;
import com.adrotation.crm.company.dto.CompanyDtos;
import com.adrotation.crm.company.entity.Company;
import com.adrotation.crm.company.entity.Contact;
import com.adrotation.crm.company.enums.ClientStatus;
import com.adrotation.crm.crm.dto.DealDtos;
import com.adrotation.crm.crm.dto.GoalOptionDto;
import com.adrotation.crm.crm.entity.Deal;
import com.adrotation.crm.crm.entity.DealPlacement;
import com.adrotation.crm.crm.entity.GoalOption;
import com.adrotation.crm.crm.enums.CalledToday;
import com.adrotation.crm.crm.enums.DocumentIntent;
import com.adrotation.crm.documents.enums.DocumentPackageType;
import com.adrotation.crm.notification.dto.NotificationDto;
import com.adrotation.crm.notification.entity.Notification;
import com.adrotation.crm.reports.dto.PhotoReportDto;
import com.adrotation.crm.reports.entity.PhotoReport;
import com.adrotation.crm.schedule.dto.ShiftDtos;
import com.adrotation.crm.schedule.dto.WeekDto;
import com.adrotation.crm.schedule.entity.Shift;
import com.adrotation.crm.schedule.entity.WeekPeriod;
import org.springframework.stereotype.Component;

import java.util.LinkedHashSet;

@Component
public class DtoMapper {

    public CityDtos.CityResponse city(City city) {
        return new CityDtos.CityResponse(
                city.getId(),
                city.getName(),
                city.getCategory(),
                city.isNeedsRepair(),
                city.getStandAddress(),
                city.getStandFormat(),
                city.getRepairStatus(),
                city.getRepairPlan(),
                city.isRotationEnabled()
        );
    }

    public CompanyDtos.CompanyResponse company(Company company) {
        return new CompanyDtos.CompanyResponse(
                company.getId(),
                company.getLegalForm(),
                company.getShortName(),
                company.getCanonicalName(),
                company.getInn(),
                company.getStatus(),
                company.getLegalAddress(),
                company.getPostalAddress(),
                company.getSettlementAccount(),
                company.getBankName(),
                company.getBankBic(),
                company.getCreatedBy() == null ? null : company.getCreatedBy().getId(),
                company.getCreatedAt()
        );
    }

    public CompanyDtos.ContactResponse contact(Contact contact) {
        return new CompanyDtos.ContactResponse(
                contact.getId(),
                contact.getCompany().getId(),
                contact.getFio(),
                contact.getPosition(),
                contact.getPhone(),
                contact.getEmail(),
                contact.getTelegramChatId(),
                contact.getViberUserId(),
                contact.getPreferredDeliveryChannel()
        );
    }

    public WeekDto week(WeekPeriod week) {
        return new WeekDto(
                week.getId(),
                week.getIsoYear(),
                week.getIsoWeekNumber(),
                week.getStartDate(),
                week.getEndDate(),
                week.getLabel(),
                week.getDriveFolderId(),
                folderUrl(week.getDriveFolderId())
        );
    }

    public ShiftDtos.ShiftResponse shift(Shift shift) {
        return new ShiftDtos.ShiftResponse(
                shift.getId(),
                shift.getCity().getId(),
                shift.getCity().getName(),
                shift.getWeek().getId(),
                shift.getWeek().getIsoWeekNumber(),
                shift.getStatus(),
                shift.getStatus().getDisplayName(),
                shift.getStatus().getColorHex(),
                shift.getCompany() == null ? null : shift.getCompany().getId(),
                shift.getCompany() == null ? null : shift.getCompany().getCanonicalName(),
                shift.getResponsiblePerson() == null ? null : shift.getResponsiblePerson().getId(),
                shift.getResponsiblePerson() == null ? null : shift.getResponsiblePerson().getFullName(),
                shift.getAutoGeneratedFromShift() == null ? null : shift.getAutoGeneratedFromShift().getId(),
                shift.isA4Sold(),
                shift.getFailureReason(),
                folderUrl(shift.getWeek().getDriveFolderId())
        );
    }

    public DealDtos.PlacementResponse placement(DealPlacement placement) {
        return new DealDtos.PlacementResponse(
                placement.getId(),
                placement.getCity().getId(),
                placement.getCity().getName(),
                placement.getStandFormat(),
                placement.getPeriodStart(),
                placement.getPeriodEnd(),
                placement.getQuantity(),
                placement.getUnitPrice(),
                placement.getDiscountPercent(),
                placement.getPromotionName(),
                placement.isVatExempt(),
                placement.getVatRate(),
                placement.getMediaType()
        );
    }

    public DealDtos.DealResponse deal(Deal deal) {
        LinkedHashSet<CityDtos.CityResponse> cities = new LinkedHashSet<>();
        deal.getTargetCities().forEach(city -> cities.add(city(city)));

        boolean baseDocumentEligible = deal.getCalledToday() == CalledToday.YES
                && deal.isGoalAchieved()
                && isDocumentIntentSelected(deal.getDocumentIntent());

        DocumentPackageType packageType = recommendedPackage(deal, baseDocumentEligible);

        return new DealDtos.DealResponse(
                deal.getId(),
                deal.getDailySequence(),
                deal.getActivityDate(),
                week(deal.getWeek()),
                company(deal.getCompany()),
                cities,
                deal.getServiceType(),
                deal.getDailyGoal() == null ? null : goal(deal.getDailyGoal()),
                deal.isGoalAchieved(),
                deal.getCalledToday(),
                deal.getDocumentIntent(),
                deal.getPlacements().stream().map(this::placement).toList(),
                baseDocumentEligible,
                packageType,
                deal.getNextCallDate(),
                deal.getNextAction(),
                deal.getNextActionDueDate(),
                deal.getNextActionCompletedAt(),
                deal.getNextAction() != null && deal.getNextActionCompletedAt() == null && deal.getNextActionDueDate() != null
                        && deal.getNextActionDueDate().isBefore(java.time.LocalDate.now()),
                deal.getComment(),
                deal.isProspective(),
                deal.getKanbanStage(),
                deal.getCreatedBy().getId(),
                deal.getCreatedBy().getFullName()
        );
    }

    public GoalOptionDto goal(GoalOption goal) {
        return new GoalOptionDto(goal.getId(), goal.getName(), goal.isActive());
    }

    public NotificationDto notification(Notification notification) {
        return new NotificationDto(
                notification.getId(),
                notification.getTriggerType(),
                notification.getEntityType(),
                notification.getEntityId(),
                notification.getDedupeKey(),
                notification.getRecipientUser() == null ? null : notification.getRecipientUser().getId(),
                notification.getRecipientRole(),
                notification.getChannel(),
                notification.getTitle(),
                notification.getPayload(),
                notification.getSentAt(),
                notification.getReadAt(),
                notification.getCreatedAt()
        );
    }

    public PhotoReportDto photo(PhotoReport report) {
        return new PhotoReportDto(
                report.getId(),
                report.getShift().getId(),
                report.getDriveFileId(),
                report.getDriveWebViewLink(),
                report.getUploadedBy().getId(),
                report.getUploadedBy().getFullName(),
                report.getCreatedAt(),
                report.getSentToClientAt()
        );
    }

    public AuditLogDto audit(AuditLog log) {
        return new AuditLogDto(
                log.getId(),
                log.getEntityType(),
                log.getEntityId(),
                log.getFieldName(),
                log.getOldValue(),
                log.getNewValue(),
                log.getAuthor() == null ? null : log.getAuthor().getId(),
                log.getAuthor() == null ? null : log.getAuthor().getFullName(),
                log.getCreatedAt()
        );
    }

    public String folderUrl(String folderId) {
        return folderId == null || folderId.isBlank()
                ? null
                : "https://drive.google.com/drive/folders/" + folderId;
    }

    private boolean isDocumentIntentSelected(DocumentIntent intent) {
        return intent == DocumentIntent.CONTRACT || intent == DocumentIntent.INVOICE;
    }

    private DocumentPackageType recommendedPackage(Deal deal, boolean eligible) {
        if (!eligible) {
            return DocumentPackageType.NONE;
        }
        if (deal.getCompany().getStatus() == ClientStatus.NEW) {
            return DocumentPackageType.CONTRACT_AND_SPECIFICATION;
        }
        if (deal.getDocumentIntent() == DocumentIntent.INVOICE) {
            return DocumentPackageType.INVOICE_OR_SPECIFICATION;
        }
        return DocumentPackageType.SPECIFICATION_ONLY;
    }
}
